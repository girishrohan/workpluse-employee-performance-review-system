"""
WorkPulse - Report & Export Service
Generates structured text, Markdown reports, and downloadable CSV deliverables from actual application data.
"""

from datetime import datetime
import pandas as pd
from services.analytics_service import compute_kpis, get_department_summary


def generate_comprehensive_report(df, selected_model_name, eval_metrics):
    """
    Generates a formal academic performance analytics report from actual loaded data.
    """
    kpis = compute_kpis(df)
    dept_sum = get_department_summary(df)

    acc = eval_metrics.get('accuracy', 0.0) * 100 if eval_metrics else 0.0
    f1 = eval_metrics.get('f1_score', 0.0) if eval_metrics else 0.0

    report_md = f"""# WorkPulse: Employee Performance Review System
## Comprehensive Executive & Academic Evaluation Report
**Generated on**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  
**Product**: WorkPulse (“Understand Performance. Empower Growth.”)  
**Academic Context**: Computer Science & Engineering (3rd Year Mini-Project)  

---

### 1. Executive Summary & Workforce Metrics
From the current dataset of **{kpis['total_employees']}** employee review records:
- **Average Attendance Rate**: {kpis['avg_attendance']}%
- **Average Task Completion Rate**: {kpis['avg_task_completion']}%
- **Average Performance Rating**: {kpis['avg_performance_score']} / 5.0

#### Performance Category Breakdown:
- 🟢 **High Performance**: {kpis['high_count']} employees ({kpis['high_pct']}%)
- 🟡 **Moderate Performance**: {kpis['moderate_count']} employees ({kpis['moderate_pct']}%)
- 🔴 **Needs Support**: {kpis['needs_support_count']} employees ({kpis['needs_support_pct']}%)

---

### 2. Departmental Performance Breakdown
| Department | Total Employees | Avg Attendance (%) | Avg Task Completion (%) | Avg Training (hrs) | High Performers (%) |
|---|---|---|---|---|---|
"""
    if not dept_sum.empty:
        for _, row in dept_sum.iterrows():
            report_md += f"| {row['department']} | {row['Total_Employees']} | {row['Avg_Attendance']} | {row['Avg_Task_Completion']} | {row['Avg_Training_Hours']} | {row['High_Performers_Pct']}% |\n"
    else:
        report_md += "| No departmental records available | - | - | - | - | - |\n"

    report_md += f"""
---

### 3. Machine Learning Model Evaluation
- **Active Classification Algorithm**: {selected_model_name}
- **Validation Strategy**: 80/20 Stratified Train-Test Split on Held-Out Records
- **Test Accuracy**: {acc:.2f}%
- **Weighted F1-Score**: {f1:.4f}
- **Primary Influencing Features**: Task Completion Rate, Attendance Rate, Previous Performance Rating

---

### 4. Ethical AI & Decision-Support Notice
> [!IMPORTANT]
> The performance categories and factor contribution insights generated by WorkPulse represent experimental statistical estimates.
> They are strictly designed as **decision-support indicators** to identify training and intervention needs.
> They must never be treated as definitive evaluations or used as the sole criteria for employment decisions.
"""
    return report_md
